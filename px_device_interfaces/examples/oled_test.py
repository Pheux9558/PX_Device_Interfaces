def main() -> None:
    cfg = USBTransportConfig(port="/dev/ttyACM0", baud=921600, debug=False, reset_on_start=True)
    gpio = GPIO_Lib(transport_config=cfg, send_ack_timeout=1)

    try:
        gpio.start()
        gpio.sync()
        

        # T-Dongle S3 I2C
        i2c = GPIO_Lib.I2C(gpio_lib=gpio, clock_pin=44, data_pin=43, frequency=400_000)

        # Arduino Uno R4 WiFi I2C Qwiic port (Wire1 on SDA=8, SCL=9)
        # i2c = GPIO_Lib.I2C(gpio_lib=gpio, i2c_bus=0)
        # i2c = GPIO_Lib.I2C(gpio_lib=gpio, i2c_bus=1)

        if True:
            # Display 128x64 OLED (SSD1306)
            display = GPIO_Lib.Display.DisplaySSD1306(
                gpio_lib=gpio,
                i2c=i2c,
                address=0x3C,
                width=128,
                height=64,
            )
        else:
            # # Display 128x32 OLED (SSD1306)
            display = GPIO_Lib.Display.DisplaySSD1306(
                gpio_lib=gpio,
                i2c=i2c,
                address=0x3C,
                width=128,
                height=32,
            )
            display.clear()
            display.set_cursor(0, 0)
            display.write_text("SSD1306 OK")
            display.set_cursor(0, 10)
            display.write_text("Wire bus 1")



        display.clear()
        display.set_cursor(0, 0)
        display.write_text("SSD1306 OK")


        
        time.sleep(.5)
        
        # Test rotation
        display.set_rotation(1)
        display.set_cursor(0, 0)
        display.clear()
        display.write_text("SSD1306 OK")
        time.sleep(.5)
        display.set_rotation(2)
        display.set_cursor(0, 0)
        display.clear()
        display.write_text("SSD1306 OK")
        time.sleep(.5)
        display.set_rotation(3)
        display.set_cursor(0, 0)
        display.clear()
        display.write_text("SSD1306 OK")
        time.sleep(.5)
        display.set_rotation(0)
        display.set_cursor(0, 0)
        display.clear()
        display.write_text("SSD1306 OK")
        time.sleep(.5)

        display.set_brightness(0)
        time.sleep(2)
        display.set_brightness(255)
        
        # Test brightness (Sweep from 255 to 0 and back to 255)
        for brightness in range(255, -1, -5):
            display.set_brightness(brightness)
            time.sleep(0.01)
        for brightness in range(0, 256, 5):
            display.set_brightness(brightness)
            time.sleep(0.01)
        


        # Draw square bitmap at (10, 20)
        bitmap_bytes = bytes(square_bitmap)
        expected = (8 * 8 + 7) // 8
        if len(bitmap_bytes) != expected:
            raise ValueError(f"Bitmap length {len(bitmap_bytes)} bytes does not match expected {expected} bytes")

        display.write_bitmap_mono(bitmap_bytes, width=8, height=8, x=10, y=20)
        time.sleep(2)
        display.write_bitmap_mono(bytes(smiley_bitmap), width=8, height=8, x=10, y=20)
        time.sleep(2)
        display.clear()


    finally:
        gpio.stop()


if __name__ == "__main__":
    main()
